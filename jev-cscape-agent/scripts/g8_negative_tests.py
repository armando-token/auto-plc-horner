@dataclass
class G8JevLadderPlan:
    """Structured Ladder Plan representation generated by Jev reasoning."""
    plan_id: str
    element_type: str        # 'CONTACT_NO', 'CONTACT_NC', 'COIL_NO'
    element_cmd: int         # 1000, 1001, 1002
    variable_name: str       # IEC 61131-3 identifier
    channel: Optional[str] = None
    confidence: float = 1.0


class PlanValidationError(ValueError):
    """Raised when a Jev plan contains an invalid or unbound identifier."""
    pass


def validate_jev_plan_strict(
    plan: G8JevLadderPlan,
    known_declarations: Set[str],
) -> Tuple[bool, Optional[str]]:
    """Strict pure-software pre-flight validation gate for Jev ladder plans."""
    ident = plan.variable_name.strip()
    # 1. IEC 61131-3 syntax validation
    if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_]{0,31}$", ident):
        return False, f"SYNTAX_ERROR: Identifier '{ident}' violates IEC 61131-3 naming rules"

    # 2. Reserved IEC keywords check
    reserved = {"PROGRAM", "FUNCTION_BLOCK", "VAR", "END_VAR", "BOOL", "INT", "REAL", "TON"}
    if ident.upper() in reserved:
        return False, f"KEYWORD_COLLISION: Identifier '{ident}' is a reserved keyword"

    # 3. Known / bound variable validation
    system_tags = {"ALW_ON", "ALW_OFF", "FST_SCN", "SYS_DISABLE", "T_100MS", "SYS_ACK", "T_10MS", "T_SEC"}
    if ident.upper() not in system_tags and ident.upper() not in {d.upper() for d in known_declarations}:
        return False, f"UNBOUND_VARIABLE: Identifier '{ident}' is not declared in the project database"

    return True, None


