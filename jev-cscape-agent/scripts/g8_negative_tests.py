def run_all_g8_negative_tests(evidence_path: Optional[Path] = None) -> int:
    """Execute complete Gate G8 Negative Verification Test Suite."""
    out_evidence = evidence_path or NEGATIVE_EVIDENCE_PATH
    out_evidence.parent.mkdir(parents=True, exist_ok=True)

    suite_start = datetime.now(timezone.utc).isoformat()
    results: List[Dict[str, Any]] = []

    # 1. Baseline Negative Control
    res_base = run_baseline_negative_control()
    results.append(res_base)
    if res_base["status"] != "success":
        logger.error("Baseline negative control failed; aborting suite fail-closed.")
        return 1

    # 2. Test N1
    results.append(run_test_n1_invalid_variable_jev_plan())

    # 3. Test N2
    results.append(run_test_n2_abort_before_save())

    # 4. Test N3
    results.append(run_test_n3_interrupted_save())

    # Post-suite Baseline Check
    base_sha_post = compute_sha256(BASE_P1_PATH)
    suite_end = datetime.now(timezone.utc).isoformat()
    all_passed = all(r.get("status") == "success" for r in results) and (base_sha_post == BASELINE_P1_SHA)

    evidence_payload: Dict[str, Any] = {
        "gate": "G8",
        "suite": "GATE_G8_NEGATIVE_VERIFICATION_TESTS",
        "timestamp_start_utc": suite_start,
        "timestamp_end_utc": suite_end,
        "status": "success" if all_passed else "failed",
        "cscape_version": "10.2 (Build 10.2.751.4)",
        "total_tests": len(results),
        "passed_tests": sum(1 for r in results if r.get("status") == "success"),
        "failed_tests": sum(1 for r in results if r.get("status") != "success"),
        "baseline_p1_sha256": BASELINE_P1_SHA,
        "baseline_verified_unmodified": (base_sha_post == BASELINE_P1_SHA),
        "tests": results,
    }

    with open(out_evidence, "w", encoding="utf-8") as f:
        json.dump(evidence_payload, f, indent=2)

    return 0 if all_passed else 1


def main() -> None:
    parser = argparse.ArgumentParser(description="Run Gate G8 Negative Verification Tests.")
    parser.add_argument("--test", choices=["BASELINE", "N1", "N2", "N3", "ALL"], default="ALL")
    parser.add_argument("--evidence", type=Path, default=NEGATIVE_EVIDENCE_PATH)
    args = parser.parse_args()

    if args.test == "ALL":
        sys.exit(run_all_g8_negative_tests(args.evidence))
    elif args.test == "BASELINE":
        sys.exit(0 if run_baseline_negative_control()["status"] == "success" else 1)
    elif args.test == "N1":
        sys.exit(0 if run_test_n1_invalid_variable_jev_plan()["status"] == "success" else 1)
    elif args.test == "N2":
        sys.exit(0 if run_test_n2_abort_before_save()["status"] == "success" else 1)
    elif args.test == "N3":
        sys.exit(0 if run_test_n3_interrupted_save()["status"] == "success" else 1)


if __name__ == "__main__":
    main()
