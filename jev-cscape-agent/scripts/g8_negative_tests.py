def run_baseline_negative_control() -> Dict[str, Any]:
    """Verify untouched p1_base.csp has 0 ladder elements and expected hash."""
    result: Dict[str, Any] = {
        "test_id": "BASELINE_NEGATIVE_CONTROL",
        "description": "Verify untouched p1_base.csp has 0 ladder elements and exact SHA-256",
        "baseline_path": str(BASE_P1_PATH),
        "expected_sha256": BASELINE_P1_SHA,
        "actual_sha256": None,
        "sha_matches": False,
        "is_ole_valid": False,
        "ladder_element_count": -1,
        "status": "failed",
        "error": None,
    }
    logger.info("Executing Baseline Negative Control on p1_base.csp...")
    try:
        assert_safety_invariants()
        actual_sha = compute_sha256(BASE_P1_PATH)
        result["actual_sha256"] = actual_sha
        result["sha_matches"] = (actual_sha == BASELINE_P1_SHA)
        if not result["sha_matches"]:
            raise RuntimeError(f"Baseline SHA mismatch! Expected {BASELINE_P1_SHA}, got {actual_sha}")

        is_ole = olefile.isOleFile(str(BASE_P1_PATH))
        result["is_ole_valid"] = is_ole
        if not is_ole:
            raise RuntimeError("Baseline file is not a valid OLE2 compound document!")

        ladder_info = parse_cfbf_ladder_elements(BASE_P1_PATH)
        elem_count = ladder_info.get("element_count", -1)
        result["ladder_element_count"] = elem_count
        if elem_count != 0:
            raise RuntimeError(f"Baseline contains {elem_count} ladder elements (expected 0)!")

        result["status"] = "success"
        logger.info("[PASS] Baseline negative control verified successfully.")
    except Exception as e:
        logger.error(f"Baseline control failed: {e}")
        result["error"] = str(e)
        result["status"] = "failed"
    return result


