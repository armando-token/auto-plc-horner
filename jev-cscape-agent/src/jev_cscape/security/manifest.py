    def __init__(self, repo_root: Optional[Path | str] = None) -> None:
        self.repo_root = Path(repo_root or Path(__file__).resolve().parents[3]).resolve()

    def generate_manifest(
        self,
        output_path: Optional[Path | str] = None,
    ) -> DeliveryManifest:
        """Scan registered artifacts, compute SHA-256 digests, and generate manifest."""
        entries: List[ArtifactManifestEntry] = []
        gate_entries: Dict[str, List[ArtifactManifestEntry]] = {g: [] for g in self.REGISTERED_PATHS}
        total_bytes = 0

        for gate, paths in self.REGISTERED_PATHS.items():
            for rel_str in paths:
                file_path = self.repo_root / rel_str
                if not file_path.is_file():
                    continue

                sha256 = compute_file_sha256(file_path)
                size = file_path.stat().st_size
                desc = self.DESCRIPTIONS.get(rel_str, f"{gate} artifact")
                posix_rel = rel_str.replace("\\", "/")

                entry = ArtifactManifestEntry(
                    relative_path=posix_rel,
                    sha256=sha256,
                    size_bytes=size,
                    gate=gate,
                    description=desc,
                )
                entries.append(entry)
                gate_entries[gate].append(entry)
                total_bytes += size

        # Compute per-gate digests and root digest
        gate_summaries: Dict[str, GateSummary] = {}
        for gate, g_items in gate_entries.items():
            g_hashes = "".join(sorted(item.sha256 for item in g_items))
            g_digest = compute_bytes_sha256(g_hashes.encode("utf-8")) if g_items else ""
            gate_summaries[gate] = GateSummary(
                gate=gate,
                file_count=len(g_items),
                total_bytes=sum(item.size_bytes for item in g_items),
                gate_digest=g_digest,
            )

        # Root digest: SHA-256 of sorted artifact hashes
        sorted_all_hashes = "".join(sorted(e.sha256 for e in entries))
        root_digest = compute_bytes_sha256(sorted_all_hashes.encode("utf-8"))

        manifest = DeliveryManifest(
            repository_root=str(self.repo_root).replace("\\", "/"),
            root_digest=root_digest,
            total_files=len(entries),
            total_bytes=total_bytes,
            gate_summaries=gate_summaries,
            artifacts=entries,
        )

        if output_path is not None:
            out_p = Path(output_path)
            out_p.parent.mkdir(parents=True, exist_ok=True)
            with open(out_p, "w", encoding="utf-8") as f:
                f.write(manifest.model_dump_json(indent=2))

        return manifest

    def verify_manifest(
        self,
        manifest_path: Path | str,
    ) -> Tuple[bool, List[str]]:
        """Verify on-disk repository files against an exported manifest.
        
        Returns:
            Tuple of (is_valid, list_of_error_descriptions).
        """
        p = Path(manifest_path)
        if not p.is_file():
            return False, [f"Manifest file not found: {p}"]

        with open(p, "r", encoding="utf-8") as f:
            data = json.load(f)

        manifest = DeliveryManifest.model_validate(data)
        errors: List[str] = []

        # 1. Verify each artifact
        for entry in manifest.artifacts:
            file_path = self.repo_root / entry.relative_path
            if not file_path.is_file():
                errors.append(f"MISSING: Artifact '{entry.relative_path}' does not exist on disk.")
                continue

            current_sha = compute_file_sha256(file_path)
            if current_sha.lower() != entry.sha256.lower():
                raw_bytes = file_path.read_bytes()
                lf_bytes = raw_bytes.replace(b"\r\n", b"\n")
                lf_sha = compute_bytes_sha256(lf_bytes)
                crlf_sha = compute_bytes_sha256(lf_bytes.replace(b"\n", b"\r\n"))
                if entry.sha256.lower() not in (lf_sha.lower(), crlf_sha.lower()):
                    errors.append(
                        f"TAMPERED: Artifact '{entry.relative_path}' SHA-256 mismatch. "
                        f"Expected {entry.sha256}, got {current_sha}."
                    )

        # 2. Verify root digest integrity
        sorted_hashes = "".join(sorted(e.sha256 for e in manifest.artifacts))
        expected_root = compute_bytes_sha256(sorted_hashes.encode("utf-8"))
        if manifest.root_digest.lower() != expected_root.lower():
            errors.append(
                f"CORRUPTED_ROOT: Manifest root digest mismatch. "
                f"Recorded: {manifest.root_digest}, calculated: {expected_root}."
            )

        is_valid = len(errors) == 0
        return is_valid, errors


